"""Benchmark behind the README Analytical Benchmark table.

OU (kappa = sigma = 1) with quadratic driver f = x^2 - (1/2)|z|^2, exact lambda = (sqrt(3) - 1) / 2.
Runs the three solvers at the settings quoted in the README, writes results/readme_benchmark.csv
and renders the README block. Takes about 4 minutes.

    python experiments/run_readme_benchmark.py           # run and rewrite the README block
    python experiments/run_readme_benchmark.py --check   # exit 1 if README is out of date with results/
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
START = "<!-- benchmark:start (generated by experiments/run_readme_benchmark.py, do not edit by hand) -->"
END = "<!-- benchmark:end -->"
OUT = ROOT / "results" / "readme_benchmark.csv"
LABELS = {
    "PDE": "PDE (n_x=500)",
    "Picard": "Picard (n=50k paths, T in [20, 40], 4 Picard iterations)",
    "Deep": "Deep TD (temporal_difference, 3000 epochs, 512 samples)",
}


def run() -> pd.DataFrame:
    from ebsde.analysis.convergence import SolverComparison

    src = (ROOT / "experiments" / "run_solver_comparison.py").read_text()
    ns: dict = {"__file__": str(ROOT / "experiments" / "run_solver_comparison.py"), "__name__": "shared_setup"}
    exec(src.split("# ---------------------------------------------------------------\n# Solver kwargs")[0], ns)
    df = SolverComparison().compare_all_solvers(
        ergodic_bsde=ns["ebsde_quad"], analytical_lambda=ns["lambda_quad"],
        pde_kwargs=dict(n_x=500, method="iteration"),
        picard_kwargs=dict(T_values=[20.0, 40.0], n_paths=50_000, n_steps_per_unit=20, n_picard=4, rng_seed=ns["RNG_SEED"]),
        deep_kwargs=dict(strategy="temporal_difference", n_epochs=3000, n_samples=512,
                         rng_seed=ns["RNG_SEED"], torch_seed=ns["TORCH_SEED"]),
    )
    df.insert(0, "lambda_exact", (np.sqrt(3) - 1) / 2)
    OUT.parent.mkdir(exist_ok=True)
    df.to_csv(OUT, index=False)
    return df


def render(df: pd.DataFrame) -> str:
    o = ["| Solver | lambda estimate | Absolute error | Relative error | Time (one run) |", "|---|---|---|---|---|"]
    for _, r in df.iterrows():
        o.append(f"| {LABELS.get(r.solver, r.solver)} | {r['lambda']:.6f} | {r.error:.1e} | {r.error / r.lambda_exact:.2%} | "
                 f"{r.time_seconds:.0f} s |")
    o += ["", f"Exact lambda = {df.lambda_exact.iloc[0]:.6f}. One run with fixed seeds on the machine described under "
          "Reproducibility; Picard and Deep are Monte Carlo methods, so their errors vary across seeds."]
    return "\n".join(o)


def main():
    readme = ROOT / "README.md"
    text = readme.read_text()
    pre, rest = text.split(START, 1)
    _, post = rest.split(END, 1)
    if "--check" in sys.argv:
        new = pre + START + "\n" + render(pd.read_csv(OUT)) + "\n" + END + post
        if new != text:
            sys.exit("README benchmark table is out of date. Run: python experiments/run_readme_benchmark.py")
        print("README benchmark table matches results/")
        return
    df = run()
    readme.write_text(pre + START + "\n" + render(df) + "\n" + END + post)
    print(render(df))


if __name__ == "__main__":
    main()
